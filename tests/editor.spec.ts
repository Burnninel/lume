import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test.use({ viewport: { width: 1440, height: 960 } })

test('rich editing preserves metadata, tables, math, diagrams and final keystrokes', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('textbox', { name: 'Conteúdo do documento' })).toBeVisible()
  await page.getByRole('button', { name: 'Markdown', exact: true }).click()
  const text = page.getByRole('textbox', { name: 'Conteúdo Markdown' })
  const frontmatter = '---\ntitle: Meu ensaio\ntags: [ideias, escrita]\n---\n'
  await text.fill(frontmatter + '# Ensaio de edição\n\nTexto **forte** e *itálico*.\n\n- [ ] Tarefa pendente\n- [x] Tarefa concluída\n\n| Nome | Valor |\n| --- | --- |\n| A | 42 |\n\n```javascript\nconst answer = 42;\n```\n\n$$\nE = mc^2\n$$\n\n```mermaid\nflowchart LR\n  A[Ideia] --> B[Escrita]\n```\n\n[Inseguro](javascript:alert(1))\n\n<script>window.__unsafe = true</script>\n')
  await page.getByRole('button', { name: 'Escrever', exact: true }).click()
  const editor = page.getByRole('textbox', { name: 'Conteúdo do documento' })
  await expect(editor.locator('h1')).toHaveText('Ensaio de edição')
  await expect(editor.locator('table.children')).toBeVisible()
  await expect(editor.locator('script, a[href^="javascript:"]')).toHaveCount(0)
  await editor.click()
  await page.keyboard.press('Control+End')
  await page.keyboard.press('Enter')
  await page.keyboard.insertText('Persistência imediata 123')
  await page.getByRole('button', { name: 'Markdown', exact: true }).click()
  await expect(text).toHaveValue(/^---\ntitle: Meu ensaio\ntags: \[ideias, escrita\]\n---\n/)
  await expect(text).toHaveValue(/Persistência imediata 123/)
  await page.getByRole('button', { name: 'Modo leitura', exact: true }).click()
  await expect(page.locator('.reader .mermaid-diagram svg')).toBeVisible({ timeout: 30_000 })
  await expect(page.locator('.reader .katex').first()).toBeVisible()
  await expect(page.locator('.reader script, .reader a[href^="javascript:"]')).toHaveCount(0)
  expect(await page.evaluate(() => (window as unknown as { __unsafe?: boolean }).__unsafe)).toBeUndefined()
  await page.reload()
  await expect(text).toHaveValue(/Persistência imediata 123/)
  expect(errors).toEqual([])
})

test('switching documents immediately never sends edits to the wrong document', async ({ page }) => {
  await page.goto('/')
  const editor = page.getByRole('textbox', { name: 'Conteúdo do documento' })
  await expect(editor).toBeVisible()
  await page.locator('input[accept=".md,.markdown,.txt"]').setInputFiles({ name: 'Outro documento.md', mimeType: 'text/markdown', buffer: Buffer.from('# Outro documento\n\nTexto independente.') })
  await expect(editor.locator('h1')).toHaveText('Outro documento')
  await page.locator('.document-select').filter({ hasText: 'Um espaço para suas ideias' }).click()
  await expect(editor.locator('h1')).toHaveText('Um espaço para suas ideias')
  await editor.click()
  await page.keyboard.press('Control+End')
  await page.keyboard.press('Enter')
  await page.keyboard.insertText('ÚLTIMA FRASE DO DOCUMENTO ORIGINAL')
  await page.locator('.document-select').filter({ hasText: 'Outro documento' }).click()
  await expect(editor.locator('h1')).toHaveText('Outro documento')
  await page.getByRole('button', { name: 'Markdown', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Conteúdo Markdown' })).not.toHaveValue(/ÚLTIMA FRASE/)
  await page.locator('.document-select').filter({ hasText: 'Um espaço para suas ideias' }).click()
  await expect(page.getByRole('textbox', { name: 'Conteúdo Markdown' })).toHaveValue(/ÚLTIMA FRASE DO DOCUMENTO ORIGINAL/)
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Conteúdo Markdown' })).toHaveValue(/ÚLTIMA FRASE DO DOCUMENTO ORIGINAL/)
})

test('find, replace, global search and self-contained HTML export work', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Markdown', exact: true }).click()
  const text = page.getByRole('textbox', { name: 'Conteúdo Markdown' })
  await text.fill('# Busca de ideias\n\nIdeia original. Outra ideia.\n\n$E=mc^2$\n\n```mermaid\nflowchart LR\nA-->B\n```')
  await page.keyboard.press('Control+f')
  await page.getByRole('textbox', { name: 'Localizar no documento' }).fill('ideia')
  await page.getByRole('textbox', { name: 'Substituir por' }).fill('palavra')
  await page.getByRole('button', { name: 'Substituir todas', exact: true }).click()
  await expect(text).toHaveValue(/Outra palavra/)
  await page.getByRole('button', { name: 'Fechar busca no documento' }).click()
  await page.keyboard.press('Control+k')
  await page.getByRole('textbox', { name: 'Buscar na biblioteca' }).fill('Outra palavra')
  await expect(page.locator('.search-results > button')).toHaveCount(1)
  await page.locator('.search-results > button').click()
  await page.getByRole('button', { name: 'Exportar', exact: true }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Página HTML', exact: true }).click()
  const html = await readFile((await (await downloadPromise).path())!, 'utf8')
  expect(html).toContain('<math')
  expect(html).toContain('flowchart LR')
  expect(html).not.toContain('Preparando diagrama')
  expect(html).not.toContain('katex-html')
})

test('mobile layout opens the document first and supports library, reading and dark theme', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Abrir biblioteca', exact: true })).toBeVisible()
  await expect(page.locator('.sidebar')).toHaveCount(0)
  await page.getByRole('button', { name: 'Abrir biblioteca', exact: true }).click()
  await expect(page.locator('.sidebar')).toBeVisible()
  await page.locator('.document-select').filter({ hasText: 'Um espaço para suas ideias' }).click()
  await expect(page.locator('.sidebar')).toHaveCount(0)
  await page.getByRole('button', { name: 'Modo leitura', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Um espaço para suas ideias', exact: true })).toBeVisible()
  await expect(page.locator('[contenteditable="true"]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Usar tema escuro', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Voltar à edição', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Conteúdo do documento' })).toBeVisible()
})
